INDEX_VERSION = 4
# Endpoints that carry a conversation: Anthropic Messages, OpenAI Chat and Responses, native Ollama.
MODEL_PATH = re.compile(r"/(?:v1/messages|chat/completions|responses|api/chat|api/generate)$")
# Agents rewrite the tail of the history between calls (Claude Code moves a reminder to the end),
# so a call still continues a thread when it differs from the thread's last call in this many trailing messages.
TAIL_SLACK = 2
# One block's text above this is cut, so a huge file read doesn't make the page unusable.
MAX_TEXT = 200_000
# Pages of turns carry this much of each text (and of each string in a tool call's input);
# the console asks for a whole turn when it's opened.
PREVIEW_TEXT = 2_000
PREVIEW_INPUT = 300
PAGE_SIZE = 60
# Threads whose turns stay parsed in memory, so paging doesn't reread a large trace.
CACHED_THREADS = 8
# Traces read at once; the ones that resend a whole conversation can be several MB each.
READ_BATCH = 25

# Claude Code says what each call is for (x-claude-code-request-class: main, subagent, auxiliary,
# compaction), which sub-agent made it, and in its system prompt's first line the call it follows
# and what started the turn (a person, or a notification such as a background task ending).
PREVIOUS_CALL = re.compile(r"\bcc_prev_req=([\w-]+)")
TURN_ORIGIN = re.compile(r"\bcc_turn_origin=(\w+)")
HINTS = {"main": "main", "subagent": "subagent"}

# What a background call is for, read from its instructions.
PURPOSES = [
    ("Suggesting your next prompt", re.compile(r"SUGGESTION MODE|what the user might (?:naturally )?type next", re.I)),
    ("Recap for when you come back", re.compile(r"stepped away and is coming back|\brecap\b", re.I)),
    ("Compacting the conversation", re.compile(r"detailed summary of the conversation|compact(?:ing|ion)? the conversation", re.I)),
    ("Describing what it's doing", re.compile(r"describe your most recent action", re.I)),
    ("Naming the session", re.compile(r"\btitle\b|naming a coding session", re.I)),
    ("Checking an action is safe", re.compile(r"security monitor|\bclassif", re.I)),
    ("Summarising", re.compile(r"\bsummar", re.I)),
    ("Checking the quota", re.compile(r"^\s*quota\s*$", re.I)),
]

# Text agents send in the user's place themselves, by how it starts (beyond the tags REMINDER knows).
AGENT_NOTES = [
    ("interrupted", re.compile(r"^\s*\[Request interrupted by user")),
    # Claude Code's summary after compacting; OpenCode's request for one and the question it goes on from.
    ("summary", re.compile(r"^\s*(?:This session is being continued from a previous conversation|Provide a detailed prompt for continuing our conversation above|What did we do so far\?\s*$)")),
    ("output", re.compile(r"^\s*<(?:local-command-stdout|bash-stdout|bash-stderr)\b")),
    ("note", re.compile(r"^\s*(?:Tool loaded\.\s*$|<total_tokens>|\[Image[: ]|Caveat: The messages below were generated by the user)")),
]
# Claude Code hands on what its user types while it works with the next tool results, explained;
# a sub-agent is told what its coordinator sends the same way.
QUEUED = re.compile(r"^\s*The user sent a new message while you were working:\n(.*?)(?:\n\nThis is how Claude Code surfaces .*)?\s*$", re.S)
COORDINATOR = re.compile(r"^\s*(?:<system-reminder[^>]*>\s*)?The coordinator sent a message while you were working:\n(.*?)\s*(?:</system-reminder>\s*)?$", re.S)
# Slash commands and ! shell commands the person ran in Claude Code.
COMMAND = re.compile(r"<command-name>\s*(.*?)\s*</command-name>", re.S)
COMMAND_ARGS = re.compile(r"<command-args>\s*(.*?)\s*</command-args>", re.S)
SHELL_INPUT = re.compile(r"^\s*<bash-input>\s*(.*?)\s*</bash-input>\s*$", re.S)


class Chats:
    def __init__(self, sessions: SessionStore):
        self.sessions = sessions
        self._locks: dict[str, threading.Lock] = {}
        self._indexes: dict[str, dict[str, Any]] = {}
        # Per thread: its newest call, how it was read, its turns, and where each chained call's reply ends in them.
        self._cache: OrderedDict[tuple[str, str], dict[str, Any]] = OrderedDict()

    def view(
        self, session: Session, records: list[dict[str, Any]], thread: str | None = None,
        before: int | None = None, limit: int = PAGE_SIZE,
    ) -> dict[str, Any]:
        """The session's threads, and a page of one thread's turns (the main chat unless thread names another).

        A page is the limit turns before position before, or the newest ones; long texts in it are previews.
        """
        lock = self._locks.setdefault(session.session_id, threading.Lock())
        with lock:
            index = self._update(session, records)
            threads, main = _threads(index)
            chosen = next((item for item in threads if item["id"] == thread), main)
            kind = _kind(chosen, main) if chosen else None
            turns = self._turns(session, chosen, kind, records) if chosen else []
        end = len(turns) if before is None else max(0, min(before, len(turns)))
        start = max(0, end - max(1, limit))
        return {
            "threads": [_summary(item, main) for item in sorted(threads, key=lambda item: item["members"][0])],
            "thread": chosen["id"] if chosen else None,
            "kind": kind,
            "total": len(turns),
            "start": start,
            # The turns at the start a sub-agent or background call was handed from the conversation it came from.
            "inherited": sum(1 for turn in turns if turn.get("inherited")),
            "turns": [_preview(turn, position) for position, turn in enumerate(turns[start:end], start)],
            "model_calls": sum(1 for record in records if _is_model_call(record)),
            "traced_calls": sum(len(item["members"]) for item in threads),
        }

    def turn(self, session: Session, records: list[dict[str, Any]], thread: str, position: int) -> dict[str, Any] | None:
        """One turn in full, for a preview that's been opened."""
        lock = self._locks.setdefault(session.session_id, threading.Lock())
        with lock:
            index = self._update(session, records)
            threads, main = _threads(index)
            chosen = next((item for item in threads if item["id"] == thread), None)
            turns = self._turns(session, chosen, _kind(chosen, main), records) if chosen else []
        if not 0 <= position < len(turns):
            return None
        return {**turns[position], "index": position}

    def forget(self, session: Session) -> None:
        self.forget_id(session.session_id)

    def forget_id(self, session_id: str) -> None:
        self._indexes.pop(session_id, None)
        for key in [key for key in self._cache if key[0] == session_id]:
            del self._cache[key]

    def _update(self, session: Session, records: list[dict[str, Any]]) -> dict[str, Any]:
        db = self.sessions.db
        index = self._indexes.get(session.session_id) or _load_index(db, session.session_id)
        seen = set(index["seen"])
        by_id = {str(record.get("request_id", "")): record for record in records}
        pending = sorted(request_id for request_id, record in by_id.items() if request_id not in seen and _is_model_call(record))
        changed = False
        for start in range(0, len(pending), READ_BATCH):
            batch = pending[start:start + READ_BATCH]
            traces = self.sessions.read_traces(session, batch)
            for request_id in batch:
                trace = traces.get(request_id)
                if trace is None:
                    # Tracing was off or the trace isn't written yet; look again next time.
                    continue
                seen.add(request_id)
                index["seen"].append(request_id)
                changed = True
                _index_call(index, request_id, trace, by_id[request_id])
        if changed:
            _save_index(db, session.session_id, index)
        self._indexes[session.session_id] = index
        return index

    def _turns(self, session: Session, thread: dict[str, Any], kind: str, records: list[dict[str, Any]]) -> list[dict[str, Any]]:
        index = self._indexes[session.session_id]
        voice = _voice(thread, kind)
        key = (session.session_id, thread["id"])
        cached = self._cache.get(key)
        if not cached or cached["voice"] != voice:
            cached = {"voice": voice, "head": None, "earlier": {}, "current": [], "ends": {}, "turns": []}
        members = sorted(rid for rid, _ in thread["requests"])
        head = members[-1]
        if cached["head"] != head:
            # Where the agent compacted the conversation, the history before is a chain of its own; each is read once.
            earlier: list[dict[str, Any]] = []
            for start in sorted(set(thread.get("eras") or [])):
                position = members.index(start) if start in members else 0
                if position == 0:
                    continue
                end = members[position - 1]
                if end not in cached["earlier"]:
                    cached["earlier"][end] = self._stitch(session, index, end, [], {})[0]
                earlier += [*cached["earlier"][end], _compacted()]
            current, ends = self._stitch(session, index, head, cached["current"], cached["ends"])
            turns = earlier + current
            if kind in ("subagent", "background") and not thread.get("eras"):
                for turn in turns[:thread.get("inherited") or 0]:
                    turn["inherited"] = True
            for turn in turns:
                # What the agent was handed from another conversation reads the way it did there.
                _attribute(turn, "person" if turn.get("inherited") else voice)
            cached.update(head=head, current=current, ends=ends, turns=turns)
        _stamp(cached["turns"], records)
        self._cache[key] = cached
        self._cache.move_to_end(key)
        while len(self._cache) > CACHED_THREADS:
            self._cache.popitem(last=False)
        return cached["turns"]

    def _stitch(
        self, session: Session, index: dict[str, Any], head: str, known: list[dict[str, Any]], ends: dict[str, int],
    ) -> tuple[list[dict[str, Any]], dict[str, int]]:
        """The conversation as of a call: its own trace's, or for a chained call the calls before it, each with its reply.

        known and ends are an earlier read of the same chain, which is kept up to the last call it shares.
        """
        links = index["links"]
        chain = [head]
        while chain[-1] not in ends and chain[-1] in links and len(chain) <= len(links):
            chain.append(links[chain[-1]])
        if chain[-1] in ends:
            kept = ends[chain.pop()]
            turns = known[:kept]
            ends = {rid: end for rid, end in ends.items() if end <= kept}
        else:
            turns, ends = [], {}
        chain.reverse()
        replies = index["replies"]
        for start in range(0, len(chain), READ_BATCH):
            batch = chain[start:start + READ_BATCH]
            traces = self.sessions.read_traces(session, batch)
            for request_id in batch:
                trace = traces.get(request_id) or {}
                request = trace.get("request") if isinstance(trace.get("request"), dict) else {}
                if not turns:
                    new = request_turns(request)
                    # Agents send replies back as they got them, so a reply's tool call ids (or text) name the call that wrote it.
                    # Calls that weren't recorded leave their replies without one.
                    for turn in new:
                        if turn["role"] == "assistant" and _reply_key(turn["blocks"]) in replies:
                            turn["request_id"] = replies[_reply_key(turn["blocks"])]
                else:
                    # A chained call sends only what's new since the call before; its system prompt is just Claude Code's header.
                    new = request_turns({"messages": request.get("messages") or []}, preamble=False)
                    if index["origins"].get(request_id) not in (None, "human"):
                        # A turn a notification started (a background task finishing, say): nobody typed it.
                        for turn in new:
                            _attribute(turn, "agent")
                turns.extend(new)
                reply = response_turn(trace.get("response"))
                if reply:
                    reply["request_id"] = request_id
                    turns.append(reply)
                ends[request_id] = len(turns)
        return turns, ends


def _index_call(index: dict[str, Any], request_id: str, trace: dict[str, Any], record: dict[str, Any]) -> None:
    request = trace.get("request")
    if not isinstance(request, dict):
        return
    messages = _messages(request)
    if not messages:
        return
    signals = _signals(trace, request)
    if signals["upstream"]:
        index["upstream"][signals["upstream"]] = request_id
    if signals["origin"]:
        index["origins"][request_id] = signals["origin"]
    thread = _place(index, request_id, messages, request, record, signals)
    index["homes"][request_id] = thread["id"]
    if not thread.get("aside"):
        for turn in request_turns(request):
            # Claude Code sends some calls with only the newest messages, so they start threads of their own;
            # their replies turning up in another thread's history put them in that thread.
            earlier = index["replies"].get(_reply_key(turn["blocks"])) if turn["role"] == "assistant" else None
            if earlier and earlier != request_id:
                index["owners"][earlier] = thread["id"]
    reply = response_turn(trace.get("response"))
    if reply:
        index["replies"][_reply_key(reply["blocks"])] = request_id


def _signals(trace: dict[str, Any], request: dict[str, Any]) -> dict[str, Any]:
    """What the agent said about a call beyond its messages: Claude Code's headers and system prompt header."""
    http = trace.get("http") if isinstance(trace.get("http"), dict) else {}
    sent = _header_map(http.get("request_headers"))
    received = _header_map(http.get("response_headers"))
    header = _plain(request.get("system"))[:4000]
    request_class = sent.get("x-claude-code-request-class", "")
    if request_class:
        # Anything that isn't the main chat or a sub-agent (auxiliary, compaction) is a call made on the side.
        hint = HINTS.get(request_class, "background")
    elif "cc_is_subagent=true" in header:
        hint = "subagent"
    else:
        hint = None
    previous = PREVIOUS_CALL.search(header)
    origin = TURN_ORIGIN.search(header)
    return {
        "hint": hint,
        "class": request_class,
        "agent": sent.get("x-claude-code-agent-id") or None,
        "previous": previous[1] if previous else None,
        "upstream": received.get("request-id") or None,
        "origin": origin[1] if origin else None,
    }


def _header_map(pairs: Any) -> dict[str, str]:
    result: dict[str, str] = {}
    for pair in pairs if isinstance(pairs, list) else []:
        if isinstance(pair, (list, tuple)) and len(pair) == 2:
            result[str(pair[0]).lower()] = str(pair[1])
    return result


def _plain(value: Any) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return "\n".join(str(part.get("text", "")) if isinstance(part, dict) else str(part) for part in value)
    return ""


def _threads(index: dict[str, Any]) -> tuple[list[dict[str, Any]], dict[str, Any] | None]:
    """The threads and the one that's the session's main chat."""
    threads = _merged(index)
    hinted = [item for item in threads if item.get("hint") == "main"]
    if hinted:
        # Claude Code marks its main chat's calls; after /clear the newest conversation is the one going on,
        # unless it's a single call (a chain broken by a call that wasn't captured).
        going = [item for item in hinted if len(item["members"]) > 1] or hinted
        return threads, max(going, key=lambda item: (item["updated"], len(item["members"])))
    candidates = [item for item in threads if not item.get("aside")] or threads
    return threads, max(candidates, key=lambda item: (len(item["members"]), item["count"]), default=None)


def _kind(thread: dict[str, Any], main: dict[str, Any] | None) -> str:
    """main, conversation (another chat of the session's), subagent or background (a call the agent made by itself)."""
    if thread is main:
        return "main"
    hint = thread.get("hint")
    if hint == "main":
        return "conversation"
    if hint == "subagent":
        return "subagent"
    if hint == "background" or thread.get("aside") or not thread.get("tools"):
        return "background"
    return "conversation"


def _voice(thread: dict[str, Any], kind: str) -> str:
    """Who wrote what a thread sends as the user, unless the text itself says otherwise."""
    if kind == "main" or thread.get("hint") == "main":
        return "person"
    return {"subagent": "parent", "background": "agent"}.get(kind, "unknown")


def _attribute(turn: dict[str, Any], voice: str) -> None:
    attached = turn.pop("attached", False)
    if turn["role"] != "user":
        return
    for block in turn["blocks"]:
        if block["type"] == "text" and "author" not in block:
            _author(block, voice, attached)


def _author(block: dict[str, Any], voice: str, attached: bool = False) -> None:
    """Says who wrote a piece of text sent as the user, and takes off the wrapping the agent put round what a person wrote.

    voice is who writes as the user in the thread; attached means the text came with tool results.
    """
    text = block["text"]
    queued = QUEUED.match(text)
    if queued:
        block.pop("reminder", None)
        block.update(text=queued[1].strip(), author="person" if voice == "person" else "agent", queued=True)
        return
    coordinator = COORDINATOR.match(text)
    if coordinator and voice == "parent":
        block.pop("reminder", None)
        block.update(text=coordinator[1].strip(), author="parent", queued=True)
        return
    command = COMMAND.search(text) if REMINDER.match(text) else None
    shell = SHELL_INPUT.match(text)
    if command or shell:
        arguments = COMMAND_ARGS.search(text) if command else None
        typed = " ".join(part for part in (command[1], arguments[1] if arguments else "") if part) if command else "!" + shell[1]
        block.pop("reminder", None)
        block.update(text=typed, author="person" if voice == "person" else "agent", command=True)
        return
    note = next((name for name, pattern in AGENT_NOTES if pattern.match(text)), None)
    if note or block.get("reminder"):
        block.update(author="agent", note=note or "reminder")
        return
    # Other text sent with tool results is the agent's, but in a sub-agent it can be its parent's (a fork's task).
    block["author"] = "agent" if attached and voice != "parent" else voice


def _stamp(turns: list[dict[str, Any]], records: list[dict[str, Any]]) -> None:
    """When each turn was sent: a reply's call's time, and for a message the time of the call that first carried it."""
    times = {str(record.get("request_id", "")): str(record["timestamp"]) for record in records if record.get("timestamp")}
    upcoming = None
    for turn in reversed(turns):
        upcoming = times.get(turn.get("request_id") or "") or upcoming
        if upcoming:
            turn["at"] = upcoming


def _compacted() -> dict[str, Any]:
    return {"role": "system", "event": "compacted", "blocks": [{
        "type": "text", "author": "agent", "note": "compacted",
        "text": "The agent compacted the conversation here: from now on the model sees a summary of what came before.",
    }]}


def _preview(turn: dict[str, Any], position: int) -> dict[str, Any]:
    """The turn as a page carries it: what the console shows folded is cut short, what people wrote is whole."""
    blocks = []
    for block in turn["blocks"]:
        folded = turn["role"] == "system" or block.get("author") in ("agent", "unknown") or block.get("reminder") or block["type"] in ("tool_result", "thinking", "other")
        if folded and isinstance(block.get("text"), str) and len(block["text"]) > PREVIEW_TEXT:
            block = {**block, "text": block["text"][:PREVIEW_TEXT], "preview": True}
        if block["type"] == "tool_use":
            shrunk = _shrink(block.get("input"))
            if shrunk != block.get("input"):
                block = {**block, "input": shrunk, "preview": True}
        blocks.append(block)
    return {**turn, "blocks": blocks, "index": position}


def _shrink(value: Any) -> Any:
    if isinstance(value, str):
        return value[:PREVIEW_INPUT]
    if isinstance(value, dict):
        return {key: _shrink(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_shrink(item) for item in value[:20]]
    return value


def _summary(thread: dict[str, Any], main: dict[str, Any] | None) -> dict[str, Any]:
    return {
        "id": thread["id"],
        "title": thread["title"],
        "model": thread["model"],
        "requests": thread["members"],
        "messages": thread["count"],
        "started": thread["started"],
        "updated": thread["updated"],
        "main": thread is main,
        "kind": _kind(thread, main),
        "purpose": thread.get("purpose") or "",
        "agent": thread.get("agent"),
    }


def _merged(index: dict[str, Any]) -> list[dict[str, Any]]:
    """The threads, with each one whose calls all went into another thread's history folded into that one."""
    by_id = {thread["id"]: {**thread, "members": [rid for rid, _ in thread["requests"]]} for thread in index["threads"]}
    owners = index["owners"]

    def home(thread_id: str) -> str:
        for _ in range(len(by_id)):
            thread = by_id[thread_id]
            targets = {owners.get(rid) for rid, _ in thread["requests"]}
            if thread.get("aside") or len(targets) != 1 or None in targets or thread_id in targets or not targets <= by_id.keys():
                return thread_id
            thread_id = targets.pop()
        return thread_id

    result: dict[str, dict[str, Any]] = {}
    for thread_id in by_id:
        target = home(thread_id)
        if target == thread_id:
            result.setdefault(thread_id, by_id[thread_id])
    for thread_id, thread in by_id.items():
        target = home(thread_id)
        if target != thread_id:
            result[target]["members"] = sorted({*result[target]["members"], *thread["members"]})
    return list(result.values())


def _place(index: dict[str, Any], request_id: str, messages: list[Any], request: dict[str, Any], record: dict[str, Any], signals: dict[str, Any]) -> dict[str, Any]:
    hashes = [_hash(message) for message in messages]
    leading = _leading_system(messages)
    timestamp = str(record.get("timestamp") or "")
    hint, agent = signals["hint"], signals["agent"]
    by_id = {thread["id"]: thread for thread in index["threads"]}
    # A background call carries the conversation it's about, but never goes on with it.
    if hint != "background":
        previous = index["upstream"].get(signals["previous"] or "")
        target = by_id.get(index["homes"].get(previous or "", ""))
        if target and not target.get("aside") and target.get("agent") == agent and target.get("hint") in (None, hint):
            if any(isinstance(message, dict) and message.get("role") == "assistant" for message in messages):
                # The whole conversation sent again: from the start, or from the summary the agent compacted it to.
                if _first(hashes, leading) != target.get("first") and len(hashes) < target["count"]:
                    target.setdefault("eras", []).append(request_id)
                _join(target, request_id, hashes, leading, len(hashes), request, timestamp)
            else:
                index["links"][request_id] = previous
                added = hashes[leading:]
                _join(target, request_id, [*target["hashes"], "reply:" + str(previous), *added], target["leading"], target["count"] + 1 + len(added), request, timestamp)
            return target
        best, best_length = None, 0
        for thread in index["threads"]:
            if thread.get("aside") or thread.get("agent") != agent or (hint and thread.get("hint") not in (None, hint)):
                continue
            previous_hashes = thread["hashes"]
            length = _common_prefix(previous_hashes, hashes)
            # The shared part must go past the system prompt (every chat shares that) and cover the old call's history.
            if length - thread["leading"] < 1 or length < len(previous_hashes) - TAIL_SLACK:
                continue
            if length > best_length or (length == best_length and best is not None and thread["updated"] >= best["updated"]):
                best, best_length = thread, length
        if best is not None:
            _join(best, request_id, hashes, leading, len(hashes), request, timestamp)
            return best
    turns = request_turns(request)
    thread = {
        "id": request_id,
        "title": _title(turns, last=hint in ("background", "subagent")),
        "model": str(request.get("model") or record.get("model") or ""),
        "requests": [[request_id, len(hashes)]],
        "hashes": hashes,
        "leading": leading,
        "first": _first(hashes, leading),
        "count": len(hashes),
        "started": timestamp,
        "updated": timestamp,
        "hint": hint,
        "agent": agent,
        "tools": bool(request.get("tools")),
        "aside": hint == "background",
        "purpose": _purpose(turns, request, signals),
        "inherited": _inherited(turns) if hint in ("background", "subagent") or not request.get("tools") else 0,
    }
    index["threads"].append(thread)
    return thread


def _join(thread: dict[str, Any], request_id: str, hashes: list[str], leading: int, count: int, request: dict[str, Any], timestamp: str) -> None:
    thread["requests"].append([request_id, count])
    thread["requests"].sort()
    thread["tools"] = bool(thread.get("tools") or request.get("tools"))
    if request_id >= max(rid for rid, _ in thread["requests"]):
        thread.update(hashes=hashes, leading=leading, first=_first(hashes, leading), count=count, updated=timestamp)
        thread["model"] = str(request.get("model") or thread["model"])


def _first(hashes: list[str], leading: int) -> str:
    return hashes[leading] if len(hashes) > leading else ""


def _inherited(turns: list[dict[str, Any]]) -> int:
    """How many turns at the start a call was handed: everything before its last message as the user, if the model had spoken before it."""
    # A forked sub-agent's task comes after the parent's history, with the result of the tool call that forked it.
    last = max((position for position, turn in enumerate(turns) if turn["role"] == "user"), default=0)
    return last if any(turn["role"] == "assistant" for turn in turns[:last]) else 0


def _purpose(turns: list[dict[str, Any]], request: dict[str, Any], signals: dict[str, Any]) -> str:
    if signals["class"] == "compaction":
        return "Compacting the conversation"
    texts = [block["text"] for turn in turns if turn["role"] == "user" for block in turn["blocks"] if block["type"] == "text" and not block.get("reminder")]
    # A background call's instructions are at the end (after the conversation it's about) or in its system prompt.
    samples = [texts[-1][:400] + "\n" + texts[-1][-400:]] if texts else []
    samples += [_plain(request.get("system"))[:1500], texts[0][:400] if texts else ""]
    for sample in samples:
        for label, pattern in PURPOSES:
            if pattern.search(sample):
                return label
    return ""


def _reply_key(blocks: list[dict[str, Any]]) -> str:
    calls = [block["id"] for block in blocks if block["type"] == "tool_use" and block.get("id")]
    if calls:
        return "tools:" + ",".join(calls)
    parts = [block.get("text", "") for block in blocks if block["type"] == "text"]
    parts += [json.dumps([block.get("name"), block.get("input")], sort_keys=True) for block in blocks if block["type"] == "tool_use"]
    return hashlib.blake2b(" ".join(" ".join(parts).split()).encode("utf-8"), digest_size=8).hexdigest()


def _common_prefix(left: list[str], right: list[str]) -> int:
    length = 0
    for a, b in zip(left, right):
        if a != b:
            break
        length += 1
    return length


def _load_index(db: Database, session_id: str) -> dict[str, Any]:
    with db.read() as connection:
        data = connection.execute(select(schema.chat_index.c.data).where(schema.chat_index.c.session_id == session_id)).scalar()
    if isinstance(data, dict) and data.get("version") == INDEX_VERSION:
        return data
    return {"version": INDEX_VERSION, "seen": [], "threads": [], "replies": {}, "owners": {}, "homes": {}, "links": {}, "upstream": {}, "origins": {}}


def _save_index(db: Database, session_id: str, index: dict[str, Any]) -> None:
    # A copy: the index in memory goes on changing while the write waits its turn.
    row = {"session_id": session_id, "data": json.loads(json.dumps(index))}
    db.writer.submit(lambda connection: kv.upsert(connection, schema.chat_index, row))


def _is_model_call(record: dict[str, Any]) -> bool:
    path = str(record.get("endpoint") or "").split("?", 1)[0].rstrip("/")
    return bool(MODEL_PATH.search(path))


def _messages(request: dict[str, Any]) -> list[Any]:
    """The conversation a call sends, in order, with the system prompt first."""
    messages: list[Any] = []
    if request.get("system"):
        messages.append({"role": "system", "content": request["system"]})
    if request.get("instructions"):
        messages.append({"role": "system", "content": request["instructions"]})
    if isinstance(request.get("messages"), list):
        messages.extend(request["messages"])
    if isinstance(request.get("input"), list):
        messages.extend(request["input"])
    elif isinstance(request.get("input"), str):
        messages.append({"role": "user", "content": request["input"]})
    if isinstance(request.get("prompt"), str):
        messages.append({"role": "user", "content": request["prompt"]})
    return messages


def _leading_system(messages: list[Any]) -> int:
    count = 0
    for message in messages:
        if not isinstance(message, dict) or message.get("role") not in ("system", "developer"):
            break
        count += 1
    return count


def _hash(message: Any) -> str:
    # System prompts change from call to call (Claude Code puts a per-call header in its own),
    # and the user's messages tell chats apart anyway.
    if isinstance(message, dict) and message.get("role") in ("system", "developer"):
        return "system"
    # Cache markers move from call to call without changing the conversation.
    text = json.dumps(_without(message, "cache_control"), sort_keys=True, ensure_ascii=False)
    return hashlib.blake2b(text.encode("utf-8"), digest_size=8).hexdigest()


def _without(value: Any, key: str) -> Any:
    if isinstance(value, dict):
        return {k: _without(v, key) for k, v in value.items() if k != key}
    if isinstance(value, list):
        return [_without(item, key) for item in value]
    return value


def _title(turns: list[dict[str, Any]], last: bool = False) -> str:
    """The first thing the person typed (for a sub-agent or background call, the last thing it was sent), skipping what agents add."""
    texts = [
        block for turn in turns if turn["role"] == "user" and (last or not turn.get("attached"))
        for block in turn["blocks"] if block["type"] == "text" and not any(pattern.match(block["text"]) for _, pattern in AGENT_NOTES)
    ]
    if last:
        texts.reverse()
    for block in [block for block in texts if not block.get("reminder")] + texts:
        text = " ".join(block["text"].split())
        if text:
            return text[:120]
    return ""


# Turns: {"role": system|user|assistant|tool, "blocks": [...]}; blocks are text, thinking,
# tool_use (id, name, input), tool_result (tool_use_id, text, is_error), image and other.

REMINDER = re.compile(r"^\s*<(system-reminder|local-command-caveat|local-command-stdout|command-name|command-message|command-args|environment_context|user_instructions)\b")


def request_turns(request: dict[str, Any], preamble: bool = True) -> list[dict[str, Any]]:
    """The turns a call sends; preamble marks the system prompts before the first message (not for a chained call's)."""
    turns: list[dict[str, Any]] = []
    for message in _messages(request):
        turn = _turn(message)
        if not turn:
            continue
        pieces = [turn]
        if turn["role"] == "user" and any(block["type"] == "tool_result" for block in turn["blocks"]):
            # Claude Code puts what it adds to tool results (an image's size, a message typed meanwhile) in the same message;
            # attached says so, as nobody typed most of it.
            results = [block for block in turn["blocks"] if block["type"] == "tool_result"]
            rest = [block for block in turn["blocks"] if block["type"] != "tool_result"]
            pieces = [{"role": "tool", "blocks": results}] + ([{"role": "user", "blocks": rest, "attached": True}] if rest else [])
        for piece in pieces:
            if turns and piece["role"] == turns[-1]["role"] and piece["role"] in ("assistant", "tool"):
                # OpenAI Responses sends a reply as several items (reasoning, text, each tool call).
                turns[-1]["blocks"].extend(piece["blocks"])
            else:
                turns.append(piece)
    if not preamble:
        return turns
    for turn in turns:
        if turn["role"] == "system":
            turn["preamble"] = True
        else:
            break
    return turns


def _turn(message: Any) -> dict[str, Any] | None:
    if not isinstance(message, dict):
        return {"role": "user", "blocks": [_text(message)]}
    kind = message.get("type")
    # OpenAI Responses items that aren't messages.
    if kind in ("function_call", "custom_tool_call", "local_shell_call"):
        return {"role": "assistant", "blocks": [_tool_use(message.get("call_id") or message.get("id"), message.get("name") or kind, message.get("arguments", message.get("input", message.get("action"))))]}
    if kind in ("function_call_output", "custom_tool_call_output", "local_shell_call_output"):
        return {"role": "tool", "blocks": [_tool_result(message.get("call_id"), message.get("output"))]}
    if kind == "reasoning":
        summary = "\n".join(str(part.get("text", "")) for part in message.get("summary") or [] if isinstance(part, dict))
        return {"role": "assistant", "blocks": [{"type": "thinking", "text": summary}]} if summary else None
    role = str(message.get("role") or "user")
    if role == "developer":
        role = "system"
    blocks = _blocks(message.get("content"))
    if message.get("reasoning_content") or message.get("thinking"):
        blocks.insert(0, {"type": "thinking", "text": str(message.get("reasoning_content") or message.get("thinking"))})
    for call in message.get("tool_calls") or []:
        if isinstance(call, dict):
            function = call.get("function") or {}
            blocks.append(_tool_use(call.get("id"), function.get("name", ""), function.get("arguments")))
    if role == "tool":
        text = "\n".join(block.get("text", "") for block in blocks)
        blocks = [_tool_result(message.get("tool_call_id") or message.get("tool_name"), text)]
    if not blocks:
        return None
    if role == "user" and all(block["type"] == "tool_result" for block in blocks):
        role = "tool"
    if role not in ("system", "user", "assistant", "tool"):
        role = "user"
    return {"role": role, "blocks": blocks}


def _blocks(content: Any) -> list[dict[str, Any]]:
    if content is None or content == "":
        return []
    if isinstance(content, str):
        return [_text(content)]
    if not isinstance(content, list):
        return [_other(content)]
    blocks = []
    for part in content:
        if isinstance(part, str):
            blocks.append(_text(part))
            continue
        if not isinstance(part, dict):
            continue
        kind = part.get("type")
        if kind in ("text", "input_text", "output_text") or (kind is None and "text" in part):
            if part.get("text"):
                blocks.append(_text(part["text"]))
        elif kind == "thinking":
            blocks.append({"type": "thinking", "text": str(part.get("thinking") or "")})
        elif kind == "redacted_thinking":
            blocks.append({"type": "thinking", "text": ""})
        elif kind in ("tool_use", "server_tool_use"):
            blocks.append(_tool_use(part.get("id"), part.get("name", ""), part.get("input")))
        elif isinstance(kind, str) and (kind == "tool_result" or kind.endswith("_tool_result")):
            inner = part.get("content")
            text = "\n".join(block.get("text", "") for block in _blocks(inner)) if isinstance(inner, list) else inner
            blocks.append(_tool_result(part.get("tool_use_id"), text, bool(part.get("is_error"))))
        elif kind in ("image", "image_url", "input_image"):
            blocks.append({"type": "image"})
        elif kind in ("document", "input_file"):
            blocks.append({"type": "other", "text": f"[{kind}]"})
        elif kind == "refusal":
            blocks.append(_text(str(part.get("refusal", ""))))
        else:
            blocks.append(_other(part))
    return blocks


def _text(value: Any) -> dict[str, Any]:
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False, indent=2)
    block = {"type": "text", **_cut(text)}
    if REMINDER.match(text):
        block["reminder"] = True
    return block


def _other(value: Any) -> dict[str, Any]:
    return {"type": "other", **_cut(json.dumps(value, ensure_ascii=False, indent=2))}


def _tool_use(call_id: Any, name: Any, arguments: Any) -> dict[str, Any]:
    if isinstance(arguments, str):
        try:
            arguments = json.loads(arguments) if arguments.strip() else {}
        except ValueError:
            pass
    return {"type": "tool_use", "id": str(call_id or ""), "name": str(name or "tool"), "input": arguments}


def _tool_result(call_id: Any, output: Any, is_error: bool = False) -> dict[str, Any]:
    text = output if isinstance(output, str) else json.dumps(output, ensure_ascii=False, indent=2) if output is not None else ""
    return {"type": "tool_result", "tool_use_id": str(call_id or ""), "is_error": is_error, **_cut(text)}


def _cut(text: str) -> dict[str, Any]:
    if len(text) <= MAX_TEXT:
        return {"text": text}
    return {"text": text[:MAX_TEXT], "truncated": len(text)}


def response_turn(response: Any) -> dict[str, Any] | None:
    """The reply a call got, put back together from its streamed events when it was streamed."""
    if isinstance(response, list):
        blocks = _streamed_blocks([event for event in response if isinstance(event, dict)])
    elif isinstance(response, dict):
        blocks = _complete_blocks(response)
    elif isinstance(response, str) and response:
        blocks = [_text(response)]
    else:
        blocks = []
    blocks = [block for block in blocks if block["type"] != "text" or block["text"]]
    return {"role": "assistant", "blocks": blocks} if blocks else None


def _complete_blocks(response: dict[str, Any]) -> list[dict[str, Any]]:
    if response.get("error"):
        error = response["error"]
        return [{"type": "error", "text": error if isinstance(error, str) else json.dumps(error, ensure_ascii=False, indent=2)}]
    if isinstance(response.get("content"), list):
        return _blocks(response["content"])
    if isinstance(response.get("output"), list):
        blocks = []
        for item in response["output"]:
            turn = _turn(item)
            if turn:
                blocks.extend(turn["blocks"])
        return blocks
    choices = response.get("choices")
    if isinstance(choices, list) and choices and isinstance(choices[0], dict):
        turn = _turn({"role": "assistant", **(choices[0].get("message") or {"content": choices[0].get("text")})})
        return turn["blocks"] if turn else []
    if isinstance(response.get("message"), dict):
        turn = _turn({**response["message"], "role": "assistant"})
        return turn["blocks"] if turn else []
    if isinstance(response.get("response"), str):
        return ([{"type": "thinking", "text": response["thinking"]}] if response.get("thinking") else []) + [_text(response["response"])]
    return [_other(response)]


def _streamed_blocks(events: list[dict[str, Any]]) -> list[dict[str, Any]]:
    # OpenAI Responses sends the whole reply once more at the end.
    for event in events:
        if event.get("type") == "response.completed" and isinstance(event.get("response"), dict):
            return _complete_blocks(event["response"])
    blocks: list[dict[str, Any]] = []
    anthropic: dict[int, dict[str, Any]] = {}
    calls: dict[int, dict[str, Any]] = {}
    text = {"thinking": "", "text": ""}

    def flush() -> None:
        for kind in ("thinking", "text"):
            if text[kind]:
                blocks.append({"type": kind, **_cut(text[kind])})
                text[kind] = ""

    for event in events:
        kind = event.get("type")
        if kind == "content_block_start":
            block = event.get("content_block") or {}
            entry = {"type": block.get("type"), "id": block.get("id"), "name": block.get("name"), "text": block.get("text") or block.get("thinking") or "", "json": ""}
            anthropic[int(event.get("index", len(anthropic)))] = entry
            blocks.append(entry)
            continue
        if kind == "content_block_delta":
            entry = anthropic.get(int(event.get("index", 0)))
            delta = event.get("delta") or {}
            if entry is not None:
                entry["text"] += delta.get("text") or delta.get("thinking") or ""
                entry["json"] += delta.get("partial_json") or ""
            continue
        if kind in ("response.output_text.delta", "response.reasoning_summary_text.delta", "response.reasoning_text.delta"):
            text["text" if kind == "response.output_text.delta" else "thinking"] += str(event.get("delta") or "")
            continue
        if kind == "error":
            flush()
            blocks.append({"type": "error", "text": json.dumps(event.get("error", event), ensure_ascii=False, indent=2)})
            continue
        message = event.get("message")
        if isinstance(message, dict):
            # Native Ollama chunks.
            text["thinking"] += str(message.get("thinking") or "")
            text["text"] += str(message.get("content") or "")
            for call in message.get("tool_calls") or []:
                flush()
                function = call.get("function") or {}
                blocks.append(_tool_use(call.get("id"), function.get("name"), function.get("arguments")))
        elif isinstance(event.get("response"), str):
            text["thinking"] += str(event.get("thinking") or "")
            text["text"] += event["response"]
        for choice in event.get("choices") or []:
            if not isinstance(choice, dict):
                continue
            delta = choice.get("delta") or {}
            text["thinking"] += str(delta.get("reasoning_content") or delta.get("reasoning") or "")
            text["text"] += str(delta.get("content") or "")
            for call in delta.get("tool_calls") or []:
                position = int(call.get("index", len(calls)))
                entry = calls.setdefault(position, {"id": "", "name": "", "arguments": ""})
                function = call.get("function") or {}
                entry["id"] = call.get("id") or entry["id"]
                entry["name"] += function.get("name") or ""
                entry["arguments"] += function.get("arguments") or ""
    flush()
    result: list[dict[str, Any]] = []
    for block in blocks:
        if block.get("type") == "tool_use" and "json" in block:
            result.append(_tool_use(block["id"], block["name"], block["json"]))
        elif block.get("type") in ("thinking", "redacted_thinking") and "json" in block:
            result.append({"type": "thinking", **_cut(block["text"])})
        elif block.get("type") == "text" and "json" in block:
            result.append(_text(block["text"]))
        elif "json" not in block:
            result.append(block)
    for position in sorted(calls):
        entry = calls[position]
        result.append(_tool_use(entry["id"], entry["name"], entry["arguments"]))
    return result
