"""A session's model calls read back as chats, the way the agent's own window shows them.

Agents resend the whole conversation with every model call, so the newest call in
a conversation holds all of it. Calls are grouped into threads by their messages:
a call continues the thread whose last call its messages start with. Claude Code
(signed in to its own account) sends most calls with only the newest messages and
names the call they follow (cc_prev_req, that call's request-id), so those calls
are chained instead and the chat is put back together from the chain.

Each thread has a kind: the session's main chat, another conversation, a sub-agent,
or a background call the agent made by itself (a title, a recap, a suggested next
prompt, a safety check). Agents send a lot as "the user" that nobody typed, so
every piece of text sent as the user says who wrote it (author: person, parent,
agent, or unknown when nothing tells), and the console can keep the person's own
messages apart from the agent's.

Traces can be large (hundreds of MB for a long session), so each session keeps a
small index (its chat_index row): per thread, the calls in it and the
hashes of its last call's messages. Only traces added since are read on a visit,
and a view reads just the traces that make up its thread.
"""

